"""Map HTTP session / user headers into agent shell environment.

Open WebUI (and similar clients) send ``X-Cursor-Session-ID`` for stateful
routing. When enabled, cursorpipe also forwards a configurable env var (default
``X_USER_ID``) to the Cursor local agent so shell/curl (e.g. open-terminal
OpenAPI with header ``x-user-id``) can read it.

The SDK's ``LocalAgentOptions`` dataclass has no ``env_vars`` field yet; we pass
``envVars`` on the wire mapping accepted by ``AgentOptions(local=...)``. A small
``.env`` file is written under the workspace as a fallback if the bridge ignores
unknown keys.
"""

from __future__ import annotations

import os
import re
from pathlib import Path

from cursorpipe._config import settings

_SESSION_DIR = ".cursorpipe/sessions"
_SAFE_ID = re.compile(r"[^a-zA-Z0-9._-]+")


def resolve_user_id_value(
    session_id: str,
    x_user_id_header: str | None = None,
) -> str:
    """Value placed in the shell env var (and open-terminal ``x-user-id``)."""
    override = (x_user_id_header or "").strip()
    if override:
        return override
    return session_id.strip()


def session_env_vars(user_id_value: str) -> dict[str, str]:
    """Env vars to inject for this session/user context."""
    name = settings.session_user_id_env_var.strip()
    if not name:
        return {}
    return {name: user_id_value}


def _safe_session_filename(session_id: str) -> str:
    cleaned = _SAFE_ID.sub("_", session_id.strip())[:200]
    return cleaned or "session"


def session_env_file_path(workspace: str | os.PathLike[str], session_id: str) -> Path:
    root = Path(workspace).resolve()
    return root / _SESSION_DIR / f"{_safe_session_filename(session_id)}.env"


def write_session_env_file(
    workspace: str | os.PathLike[str],
    session_id: str,
    env_vars: dict[str, str],
) -> Path | None:
    """Write ``export KEY='value'`` lines for shell ``source`` fallback."""
    if not env_vars:
        return None
    path = session_env_file_path(workspace, session_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by cursorpipe — do not commit secrets here."]
    for key, value in env_vars.items():
        escaped = value.replace("'", "'\"'\"'")
        lines.append(f"export {key}='{escaped}'")
    lines.append(f"export CURSORPIPE_SESSION_ENV_FILE='{path}'")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def merge_local_options_with_env(
    local_wire: dict,
    env_vars: dict[str, str],
    env_file: Path | None,
) -> dict:
    """Return a local-options mapping with ``envVars`` for AgentOptions(local=...)."""
    merged = dict(local_wire)
    wire_env = dict(env_vars)
    if env_file is not None:
        wire_env["CURSORPIPE_SESSION_ENV_FILE"] = str(env_file)
    if wire_env:
        merged["envVars"] = wire_env
    return merged
